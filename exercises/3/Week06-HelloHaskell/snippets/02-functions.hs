-- main е входната точка на програмата. Типът IO () означава
-- "действие, което общува с външния свят и не връща стойност".
main :: IO()
main = do
    -- f $ x е същото като f (x) - $ спестява скобите около аргумента.
    print $ "Hello world!"
    print "Hello world!"
    print $ 2
    print $ 2 + 3
    print $ f 5
    print $ g 1 2
    -- Отрицателен аргумент се огражда в скоби - иначе "f -5" се чете като f минус 5.
    print $ f (-5)
    -- print $ f -5 -- грешка
    print $ g (-1) 2

-- Сигнатура: f приема Int и връща Int.
f :: Int -> Int
f n = n + 1

-- Функция с два аргумента: стрелките се четат отдясно наляво -
-- последният тип е резултатът, останалите са аргументите.
g :: Int -> Int -> Int
g a b = 2 * a + b
