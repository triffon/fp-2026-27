main :: IO()
main = do
    -- Диапазони: [a .. b] изброява от a до b включително,
    -- а [a, c .. b] - със стъпка c - a.
    print $ [1 .. 5]
    print $ [1, 3 .. 6]
    -- List comprehension: [израз | генератор, условия].
    -- За всяко x от списъка пресмятаме израза отляво ...
    print $ [x + 10 | x <- [1 .. 6]]
    -- ... като можем да филтрираме с едно или повече условия след запетая.
    print $ [x | x <- [1 .. 6], even x]
    print $ [x | x <- [1 .. 6], mod x 3 == 0 && x > 3]
