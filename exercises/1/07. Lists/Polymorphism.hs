-- 1. Параметричен полиморфизъм

-- Подобно на това, което сме правили
-- в C++ с шаблони, в Haskell също имаме
-- начин да правим функциите си полиморфни,
-- и то по доста по-лесен и естествен начин:

-- дължината на списъка не зависи от типа
-- на елементите в него
length' :: [a] -> Int
length' [] = 0
length' (_:xs) = 1 + length' xs

-- Можем да използваме различни имена
-- на типовите параметри, за да указваме
-- зависимости между тях:

map' :: (a -> b) -> [a] -> [b]
map' _ [] = []
map' f (x:xs) = f x : map' f xs

-- В горната функция a и b са различни
-- типови параметри, т.е. могат да бъдат
-- както различни, така и еднакви, например:

