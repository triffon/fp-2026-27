module Intro where

-- За разлика от Scheme, Haskell е:
-- > силно и статично типизиран;
-- > ленив по подразбиране;
-- > функциите не могат да имат странични ефекти.

-- Тъй като Haskell е статично типизиран,
-- ще трябва експлицитно да пишем типове
-- на функциите и константите, които дефинираме.
-- Типовете в Haskell винаги започват с главна буква.
-- Имаме вградени следните типове: Int, Integer, Float,
-- Double, Bool, String, [Int], [Char], (Int, String) и т.н.

-- Забележка: String е същото като [Char].

-- Забележка: Дори и да е статично типизиран,
-- Haskell все пак може да извежда типовете
-- на повечето константи/функции напълно сам.
-- Обаче е по-полезно, ако сами си изписвате
-- типовете (защото понякога изведените такива
-- няма да са тези, които реални искате).

-- За да дефинираме константи, първо пишем техния
-- тип, а след това и тяхната дефиниция:

a :: Int
a = 10

b, c :: Bool
b = True
c = False

константа :: String
константа = "низовете в Haskell са unicode"

pair :: (Int, String)
pair = (42, "the answer to the universe")

-- >>> fst pair
-- 42

-- >>> snd pair
-- "the answer to the universe"

-- Оценката на константа е самата константа:

-- >>> a
-- 10

-- >>> константа
-- "\1085\1080\1079\1086\1074\1077\1090\1077 \1074 Haskell \1089\1072 unicode"


-- Функции дефинираме по аналогичен начин,
-- като изписваме типовете на аргументите
-- и типа на връщания резултат, разделени със стрелки.
-- Изброяваме аргументите на функцията с празни места
-- и дефинираме тялото ѝ чрез някакъв израз.
-- Забележете, че = се използва за дефиниция, а не -
-- за сравнение.

-- Едноместна функция, която приема Int и връща Int
add1 :: Int -> Int
add1 x = x + 1

-- Прилагането на функция е подобно на Scheme,
-- т.е. използват се празни места за него,
-- но вече няма да имаме нужда (винаги) от скоби:

-- >>> add1 10
-- 11

-- Скоби ще използваме САМО за приоритет.

-- Двуместна функция:
divide :: Double -> Double -> Double
divide x y =
  if y == 0
    then error "cannot divide by 0"
    else x / y

-- За разлика от Scheme, освен if-then-else
-- имаме още 3 вида условни операции:

-- if-then-else
isZero1 :: Int -> Bool
isZero1 x = if x == 0 then True else False -- или само x == 0

-- guards (пазачи); аналог на cond
isZero2 :: Int -> Bool
isZero2 x
  | x == 0 = True
  | otherwise = False

-- pattern matching
isZero3 :: Int -> Bool
isZero3 0 = True
isZero3 x = False -- или _, ако не го използваме

-- case-of
isZero4 :: Int -> Bool
isZero4 x =
  case x of
    0 -> True
    x -> False -- или _, ако не го използваме

-- Можем да правим и локални дефиниции в Haskell,
-- използвайки where клаузи и let-bindings:

fooWhere :: Int -> Int
fooWhere n = bar + baz * qux
  where
    bar = n * 10 + 20
    baz = n ^ 2
    qux = bar + baz

fooLet :: Int -> Int
fooLet n = let bar = n * 10 + 20
               baz = n ^ 2
               qux = bar + baz
             in bar + baz * qux

-- Отговарят на define и letrec в Scheme.

